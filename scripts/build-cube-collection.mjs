import fs from 'node:fs';
import { readCollection } from './collection-source.mjs';

const sourcePath = process.argv[2];
if (!sourcePath) {
  console.error('usage: node scripts/build-cube-collection.mjs <立体几何.md>');
  process.exit(1);
}

const ids = ['018', '020', '032', '040', '049', '055', '061'];
const markdown = fs.readFileSync(sourcePath, 'utf8');
const { problems, rendered, figures } = readCollection(markdown, ids, '正方体', /正方体/, ['018', '032']);
const meta = {
  sourceRepo: 'https://github.com/cheng-bai/shanghai-math-essay-collection',
  volume: '分册/立体几何.md',
  volumeUrl: 'https://github.com/cheng-bai/shanghai-math-essay-collection/blob/main/分册/立体几何.md',
  note: '只收录题干为正方体的 7 题。公开发布不代表对原试题与题图拥有排他版权。',
  figures,
  problems,
};
const js = `// Generated by scripts/build-cube-collection.mjs. MathML is pre-rendered; figure URLs point at the collection site.\nwindow.CUBE_COLLECTION = ${JSON.stringify(rendered)};\n`;
const dataDir = new URL('../data/', import.meta.url);
fs.mkdirSync(dataDir, { recursive: true });
fs.writeFileSync(new URL('cube-collection.json', dataDir), `${JSON.stringify(meta, null, 2)}\n`);
fs.writeFileSync(new URL('cube-collection.js', dataDir), js);
console.log(`problems ${problems.length}, figures ${figures.length}, js ${js.length} bytes`);
